//! Every visible string of the iced prototype, in one place.
//!
//! The Tauri prototype keeps the same table in `dist/i18n.js`; keeping the keys
//! parallel is the point — the comparison is how much effort each toolkit makes
//! this. Data that comes back from the core (paths, diagnostics, the `switch`
//! refusal) is deliberately *not* translated here: it is reported exactly as the
//! engine produced it, in both prototypes.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En,
    Zh,
}

impl Lang {
    pub fn toggled(self) -> Self {
        match self {
            Self::En => Self::Zh,
            Self::Zh => Self::En,
        }
    }
}

